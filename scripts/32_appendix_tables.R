# Tabelas do apêndice em markdown (para inclusão no Quarto).
suppressPackageStartupMessages(library(data.table))
OUT <- "article/tables"; dir.create(OUT, showWarnings = FALSE, recursive = TRUE)
md <- function(dt, file, caption) {
  hdr <- paste0("| ", paste(names(dt), collapse = " | "), " |")
  sep <- paste0("|", paste(rep("---:", ncol(dt)), collapse = "|"), "|")
  body <- apply(dt, 1, function(r) paste0("| ", paste(r, collapse = " | "), " |"))
  writeLines(c(hdr, sep, body, "", paste0(": ", caption)), file.path(OUT, file))
}
